"""
Checks for Proposition 4.18 of Pham-Timmins (W_{>=-1}, orbit homomorphism Psi_n).

For n = 1,2,3 and each weight w (e_0-eigenvalue) up to N:
  K2_w  = dim (ker Psi_n  cap  U_2)_w
  S2_w  = dim S^2(W/J)_w = #{(a,b): n <= a <= b, a+b = w}        (J = <e_-1..e_{n-1}>)
  H_w   = #{l >= n : 2l <= w}                                     (weights of F_{2n}+F_{2n+2}+...)
  M_w   = dim of the ad(W)-submodule generated by Omega^{(2n+2)}_{2n+1,-1}, in weight w
Also: Omega in ker, Omega symmetric (in sym S^2), ker cap U_1 = 0.
Exact arithmetic mod a large prime.
"""
import sys
from functools import lru_cache
from math import comb

P = 2147483629
N = int(sys.argv[1]) if len(sys.argv) > 1 else 12
BUF = int(sys.argv[2]) if len(sys.argv) > 2 else 6
sys.setrecursionlimit(100000)


def addto(d, k, c):
    c %= P
    if c:
        v = (d.get(k, 0) + c) % P
        if v:
            d[k] = v
        else:
            d.pop(k, None)


# ---- U(W_{>=-1}) PBW (nondecreasing index tuples), [e_i,e_j]=(j-i)e_{i+j}
@lru_cache(None)
def normal(word):
    for i in range(len(word) - 1):
        a, b = word[i], word[i + 1]
        if a > b:
            res = {}
            for m, c in normal(word[:i] + (b, a) + word[i + 2:]):
                addto(res, m, c)
            if b - a:
                for m, c in normal(word[:i] + (a + b,) + word[i + 2:]):
                    addto(res, m, c * (b - a))
            return tuple(res.items())
    return ((word, 1),)


def umul(x, y):
    res = {}
    for mx, cx in x.items():
        for my, cy in y.items():
            for m, c in normal(mx + my):
                addto(res, m, cx * cy * c)
    return res


def gen(i):
    return {(i,): 1}


def br(x, y):
    r = umul(x, y)
    for m, c in umul(y, x).items():
        addto(r, m, -c)
    return r


# ---- T_n = A_1 (x) U(g_n), g_n = <v_0..v_{n-1}>, [v_i,v_j]=(j-i)v_{i+j} (0 if i+j>=n)
def make_T(n):
    @lru_cache(None)
    def vnormal(word):
        for i in range(len(word) - 1):
            a, b = word[i], word[i + 1]
            if a > b:
                res = {}
                for m, c in vnormal(word[:i] + (b, a) + word[i + 2:]):
                    addto(res, m, c)
                if a + b < n and b - a:
                    for m, c in vnormal(word[:i] + (a + b,) + word[i + 2:]):
                        addto(res, m, c * (b - a))
                return tuple(res.items())
        return ((word, 1),)

    def ff(x, k):
        r = 1
        for j in range(k):
            r *= x - j
        return r

    def tmul(x, y):
        res = {}
        for (a, b, V), cx in x.items():
            for (a2, b2, V2), cy in y.items():
                vprod = vnormal(V + V2)
                for k in range(min(b, a2) + 1):
                    coef = comb(b, k) * ff(a2, k)
                    for Vm, cv in vprod:
                        addto(res, (a + a2 - k, b - k + b2, Vm), cx * cy * coef * cv)
        return res

    def psi_e(i):
        d = {}
        if i + 1 >= 0:
            addto(d, (i + 1, 1, ()), 1)
        for j in range(n):
            if i - j >= 0:
                addto(d, (i - j, 0, (j,)), comb(i + 1, j + 1))
        return d

    @lru_cache(None)
    def psi_mono(m):
        if not m:
            return (((0, 0, ()), 1),)
        prev = dict(psi_mono(m[:-1]))
        return tuple(tmul(prev, psi_e(m[-1])).items())

    def psi(x):
        res = {}
        for m, c in x.items():
            for k, v in psi_mono(m):
                addto(res, k, c * v)
        return res

    return psi


class Span:
    def __init__(self):
        self.rows = {}

    def reduce(self, v):
        v = dict(v)
        while v:
            piv = max(v)
            if piv in self.rows:
                c = v[piv]
                for k, val in self.rows[piv].items():
                    addto(v, k, -c * val)
            else:
                return v
        return v

    def add(self, v):
        r = self.reduce(v)
        if not r:
            return False
        piv = max(r)
        inv = pow(r[piv], P - 2, P)
        self.rows[piv] = {k: val * inv % P for k, val in r.items()}
        return True

    def __len__(self):
        return len(self.rows)


def u2_basis(w):
    """PBW basis of weight-w part of U_2(W_{>=-1})."""
    B = []
    if w == 0:
        B.append(())
    if w >= -1:
        B.append((w,))
    for a in range(-1, w + 2):
        b = w - a
        if b >= a and a >= -1:
            B.append((a, b))
    return B


def kernel_dims(psi, w):
    basis = sorted(u2_basis(w), key=lambda m: (len(m), m))
    img_span = {}
    ker1 = ker2 = 0
    for m in basis:
        img = dict(psi({m: 1}))
        while img:
            piv = max(img)
            if piv in img_span:
                iv = img_span[piv]
                c = img[piv] * pow(iv[piv], P - 2, P)
                for k, val in iv.items():
                    addto(img, k, -c * val)
            else:
                break
        if img:
            img_span[max(img)] = img
        else:
            if len(m) <= 1:
                ker1 += 1
            ker2 += 1
    return ker1, ker2


def omega(m, k, s):
    res = {}
    for i in range(m + 1):
        for mm, c in umul(gen(k - i), gen(s + i)).items():
            addto(res, mm, c * (-1) ** i * comb(m, i))
    return res


def weight_of(x):
    m = next(iter(x))
    return sum(m)


def admodule(gen_elt, top):
    """ad(W)-submodule generated by gen_elt, using e_-1, e_1, e_2 (they generate W_{>=-1};
    e_0 acts by a scalar on weight vectors), computed inside weights <= top."""
    spans = {}
    w0 = weight_of(gen_elt)
    frontier = [gen_elt]
    spans.setdefault(w0, Span()).add(gen_elt)
    while frontier:
        new = []
        for x in frontier:
            wx = weight_of(x)
            for k in (-1, 1, 2):
                if wx + k > top:
                    continue
                y = br(gen(k), x)
                if not y:
                    continue
                S = spans.setdefault(wx + k, Span())
                r = S.reduce(y)
                if r:
                    S.add(r)
                    new.append(r)
        frontier = new
    return {w: len(S) for w, S in spans.items()}


