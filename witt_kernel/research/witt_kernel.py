"""
Kernel of the orbit homomorphism Psi_1 restricted to U(W_{>=1}).

W_{>=1} = span{e_i : i >= 1},  [e_i, e_j] = (j - i) e_{i+j},  e_i = t^{i+1} d.
Psi_1 : e_i -> t^{i+1} d + (i+1) t^i v,   target T_1 = A_1 [v]  (v central).

U(W_{>=1}) is graded by weight (ad e_0 eigenvalue = sum of indices), and each
weight space is finite-dimensional (PBW basis = partitions of w).  So for each w
we compute exactly (mod a large prime):
  K_w        = ker Psi_1 in weight w, filtered by PBW order
  J_w        = sum_i ( e_i K_{w-i} + K_{w-i} e_i )   (what lower weights generate)
  new gens   = K_w / J_w, split by order
and test whether the ideal generated by differentiators equals the kernel.
"""
import sys
from functools import lru_cache
from math import comb

P = int(sys.argv[1]) if len(sys.argv) > 1 else 2147483629
N = int(sys.argv[2]) if len(sys.argv) > 2 else 16
sys.setrecursionlimit(100000)


def addto(d, k, c):
    c %= P
    if c:
        v = (d.get(k, 0) + c) % P
        if v:
            d[k] = v
        else:
            d.pop(k, None)


# ---------- U(W_{>=1}) in PBW basis (nondecreasing index tuples) ----------
@lru_cache(None)
def normal(word):
    for i in range(len(word) - 1):
        a, b = word[i], word[i + 1]
        if a > b:
            res = {}
            for m, c in normal(word[:i] + (b, a) + word[i + 2:]):
                addto(res, m, c)
            for m, c in normal(word[:i] + (a + b,) + word[i + 2:]):
                addto(res, m, c * (b - a))
            return tuple(res.items())
    return ((word, 1),)


def umul(x, y):
    res = {}
    for mx, cx in x.items():
        for my, cy in y.items():
            for m, c in normal(mx + my):
                addto(res, m, cx * cy * c)
    return res


def gen(i):
    return {(i,): 1}


# ---------- T_1 = A_1[v], basis t^a d^b v^c ----------
def ff(n, k):
    r = 1
    for j in range(k):
        r *= n - j
    return r


def tmul(x, y):
    res = {}
    for (a, b, c), cx in x.items():
        for (a2, b2, c2), cy in y.items():
            for k in range(min(b, a2) + 1):
                coef = comb(b, k) * ff(a2, k)
                addto(res, (a + a2 - k, b - k + b2, c + c2), cx * cy * coef)
    return res


def psi_e(i):
    return {(i + 1, 1, 0): 1, (i, 0, 1): i + 1}


@lru_cache(None)
def psi_mono(m):
    if not m:
        return ((((0, 0, 0)), 1),)
    prev = dict(psi_mono(m[:-1]))
    return tuple(tmul(prev, psi_e(m[-1])).items())


def psi(x):
    res = {}
    for m, c in x.items():
        for k, v in psi_mono(m):
            addto(res, k, c * v)
    return res


# ---------- linear algebra mod P on sparse dict vectors ----------
class Span:
    def __init__(self):
        self.rows = {}  # pivot -> vector with coeff 1 at pivot

    def reduce(self, v):
        v = dict(v)
        changed = True
        while v:
            piv = max(v)  # pivot = largest key
            if piv in self.rows:
                c = v[piv]
                for k, val in self.rows[piv].items():
                    addto(v, k, -c * val)
            else:
                return v
        return v

    def add(self, v):
        r = self.reduce(v)
        if not r:
            return False
        piv = max(r)
        inv = pow(r[piv], P - 2, P)
        r = {k: val * inv % P for k, val in r.items()}
        self.rows[piv] = r
        return True

    def __len__(self):
        return len(self.rows)

    def basis(self):
        return list(self.rows.values())


def partitions(w, maxpart=None):
    if maxpart is None:
        maxpart = w
    if w == 0:
        yield ()
        return
    for p in range(min(w, maxpart), 0, -1):
        for rest in partitions(w - p, p):
            yield rest + (p,)  # nondecreasing


def key(m):
    # order PBW monomials by (length, indices) so pivots favour high order;
    # kernel vectors with low order then appear first when sorted by length.
    return (len(m), m)


def kernel_by_order(w):
    """Return list of kernel vectors of weight w, each tagged with its PBW order."""
    monos = sorted(partitions(w), key=key)
    img_span = {}  # pivot -> (image vector, combination)
    kernel = []
    for m in monos:
        img = dict(psi({m: 1}))
        comb_ = {m: 1}
        while img:
            piv = max(img)
            if piv in img_span:
                iv, cv = img_span[piv]
                c = img[piv] * pow(iv[piv], P - 2, P)
                for k, val in iv.items():
                    addto(img, k, -c * val)
                for k, val in cv.items():
                    addto(comb_, k, -c * val)
            else:
                break
        if img:
            img_span[max(img)] = (img, comb_)
        else:
            kernel.append((len(m), comb_))
    return kernel, len(monos)


def omega(m, k, s):
    res = {}
    for i in range(m + 1):
        x = umul(gen(k - i), gen(s + i))
        for mm, c in x.items():
            addto(res, mm, c * (-1) ** i * comb(m, i))
    return res


def weight(x):
    return sum(next(iter(x)))


def ideal_closure(gens_by_w, N):
    """Weight pieces of the two-sided ideal of U(W>=1) generated by gens."""
    I = {}
    for w in range(1, N + 1):
        S = Span()
        for i in range(1, w):
            if w - i in I:
                for x in I[w - i].basis():
                    S.add(umul(gen(i), x))
                    S.add(umul(x, gen(i)))
        for g in gens_by_w.get(w, []):
            S.add(g)
        I[w] = S
    return I


